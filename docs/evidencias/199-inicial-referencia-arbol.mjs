import fs from 'node:fs';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../../', import.meta.url));
const run = (command,args) => { const r = spawnSync(command,args,{cwd:root,encoding:'utf8',maxBuffer:16*1024**2});assert.equal(r.status,0,r.stderr);return r.stdout.trim(); };
const commit = run('git',['rev-parse','HEAD']);
const base = 'fa3b492b8f1d6a77433a92f4d63b665cfea3747c';
const localTree = run('git',['rev-parse','HEAD^{tree}']);
const remote = JSON.parse(run('gh',['api',`repos/akproduccioneseventos/app-AK/git/trees/${commit}?recursive=1`]));
assert.equal(remote.truncated,false);assert.equal(remote.sha,localTree);
const changed = run('git',['diff','--name-only',base,commit]).split('\n').filter(Boolean);
assert.ok(changed.every(name=>name==='ESTADO-ACTUAL.md'||name.startsWith('docs/')), 'Audit must not change app');
const blobs = new Map(remote.tree.filter(row=>row.type==='blob').map(row=>[row.path,row.sha]));
const verified = changed.map(file=>{const sha=run('git',['rev-parse',`${commit}:${file}`]);assert.equal(blobs.get(file),sha,file);return{file,sha};});
const pr = JSON.parse(run('gh',['api','repos/akproduccioneseventos/app-AK/pulls/1350','--jq','{state:.state,draft:.draft,head:.head.sha}']));
assert.equal(pr.state,'open');assert.equal(pr.draft,true);assert.equal(pr.head,commit);
const order = 'docs/ordenes/210-portal-cliente-pagos-entregas-cancelacion.md';
assert.ok(verified.some(row=>row.file===order));
const receipt={commit,base,localTree,remoteTree:remote.sha,pr:1350,prState:pr.state,draft:pr.draft,verifiedCount:verified.length,verified,appChanged:false,checkedAt:new Date().toISOString(),claim:'Remote content delivery only; not app acceptance or coder execution.'};
fs.writeFileSync(new URL('199-entrega-verificada.json',import.meta.url),JSON.stringify(receipt,null,2)+'\n');
console.log(JSON.stringify({...receipt,verified:undefined}));
