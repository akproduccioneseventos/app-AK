#!/usr/bin/env node
/**
 * generate-firebase-messaging-sw.mjs
 *
 * Generates public/firebase-messaging-sw.js from environment variables.
 *
 * If all required Firebase variables are present → generates a real FCM service worker.
 * If any variable is missing → generates a safe no-op service worker that does NOT
 * initialize Firebase and does NOT break the app.
 *
 * Usage: node scripts/generate-firebase-messaging-sw.mjs
 *
 * Required env vars:
 *   NEXT_PUBLIC_FIREBASE_API_KEY
 *   NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN
 *   NEXT_PUBLIC_FIREBASE_PROJECT_ID
 *   NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET
 *   NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID
 *   NEXT_PUBLIC_FIREBASE_APP_ID
 */

import { writeFileSync, mkdirSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUTPUT_PATH = resolve(__dirname, '../public/firebase-messaging-sw.js');

// Load .env files if present (best-effort, not required in CI/CD)
try {
  const { config } = await import('dotenv');
  config({ path: resolve(__dirname, '../.env.local'), override: false });
  config({ path: resolve(__dirname, '../.env'), override: false });
} catch {
  // dotenv not available — rely on environment variables already set
}

const apiKey = process.env.NEXT_PUBLIC_FIREBASE_API_KEY;
const authDomain = process.env.NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN;
const projectId = process.env.NEXT_PUBLIC_FIREBASE_PROJECT_ID;
const storageBucket = process.env.NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET;
const messagingSenderId = process.env.NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID;
const appId = process.env.NEXT_PUBLIC_FIREBASE_APP_ID;

const requiredVars = { apiKey, authDomain, projectId, storageBucket, messagingSenderId, appId };
const missingVars = Object.entries(requiredVars)
  .filter(([, v]) => !v || v.startsWith('REEMPLAZAR-CON'))
  .map(([k]) => k);

let content;

if (missingVars.length === 0) {
  console.log('[generate-firebase-messaging-sw] ✅ All Firebase variables found. Generating real FCM service worker.');

  content = `// public/firebase-messaging-sw.js
// Auto-generated by scripts/generate-firebase-messaging-sw.mjs — DO NOT EDIT MANUALLY.
// Firebase Cloud Messaging Service Worker

importScripts('https://www.gstatic.com/firebasejs/10.12.2/firebase-app-compat.js');
importScripts('https://www.gstatic.com/firebasejs/10.12.2/firebase-messaging-compat.js');

// Firebase public config — these values are public (NOT secrets).
// Generated at build time from environment variables.
const firebaseConfig = {
  apiKey: ${JSON.stringify(apiKey)},
  authDomain: ${JSON.stringify(authDomain)},
  projectId: ${JSON.stringify(projectId)},
  storageBucket: ${JSON.stringify(storageBucket)},
  messagingSenderId: ${JSON.stringify(messagingSenderId)},
  appId: ${JSON.stringify(appId)},
};

try {
  firebase.initializeApp(firebaseConfig);
  const messaging = firebase.messaging();

  // Handle background messages
  messaging.onBackgroundMessage((payload) => {
    const title = payload.notification?.title || 'AK Producciones';
    const options = {
      body: payload.notification?.body || '',
      icon: '/icons/icon-192x192.png',
      badge: '/icons/icon-192x192.png',
      data: payload.data || {},
    };
    self.registration.showNotification(title, options);
  });
} catch (err) {
  console.warn('[firebase-messaging-sw] Firebase initialization failed:', err && err.message);
}
`;
} else {
  console.warn(
    `[generate-firebase-messaging-sw] ⚠️ Missing Firebase variables: ${missingVars.join(', ')}. Generating safe no-op service worker.`
  );

  content = `// public/firebase-messaging-sw.js
// Auto-generated by scripts/generate-firebase-messaging-sw.mjs — DO NOT EDIT MANUALLY.
// SAFE NO-OP: Firebase configuration is not available.
// Push notifications are disabled. The app will work normally without them.

self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', (event) => event.waitUntil(self.clients.claim()));

// No Firebase initialization — FCM variables were not set at build time.
`;
}

// Ensure public directory exists
mkdirSync(resolve(__dirname, '../public'), { recursive: true });

writeFileSync(OUTPUT_PATH, content, 'utf-8');
console.log(`[generate-firebase-messaging-sw] Written to: ${OUTPUT_PATH}`);
